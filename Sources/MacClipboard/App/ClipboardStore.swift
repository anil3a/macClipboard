import AppKit
import Combine
import CryptoKit

/// Watches the system pasteboard and keeps the history:
/// - up to `settings.historyLimit` unpinned items (oldest dropped first); pinned items are never dropped
/// - everything is stored encrypted on disk, so history survives restarts (unless turned off)
/// - only metadata and small thumbnails stay in memory; full data is loaded when pasting
final class ClipboardStore: ObservableObject {
    /// Largest single copy we keep (very long text, big images). Bigger copies fall back to their basic types.
    static let maxItemBytes = 256 * 1024 * 1024

    /// Pasteboard markers that password managers and similar apps use to say "don't record this".
    private static let ignoredMarkerTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
        "com.typeit4me.clipping",
        "Pasteboard generator type",
        "net.antelle.keeweb",
    ]

    /// Copies made while one of these apps is in front are ignored (if the setting is on).
    private static let passwordManagerBundleIDs: Set<String> = [
        "com.apple.Passwords",
        "com.apple.keychainaccess",
        "com.1password.1password",
        "com.agilebits.onepassword7",
        "com.bitwarden.desktop",
        "org.keepassxc.keepassxc",
        "com.lastpass.LastPass",
        "in.sinew.Enpass-Desktop",
        "com.dashlane.dashlanephonefinal",
        "me.proton.pass.electron",
    ]

    /// Types kept when a copy is larger than `maxItemBytes`.
    private static let essentialTypes: Set<String> = [
        ItemAnalyzer.fileURL, ItemAnalyzer.utf8Text, ItemAnalyzer.rtf, "public.png",
    ]

    @Published private(set) var items: [ClipboardItem] = []
    @Published private(set) var diskUsage: Int = 0
    /// Set when history can't be saved across restarts (e.g. Keychain access was denied).
    @Published private(set) var storageProblem: String?

    var hasUnpinnedItems: Bool { items.contains { !$0.isPinned } }

    private let settings: AppSettings
    private let storage: HistoryStorage
    private let isPersistent: Bool
    private let io = DispatchQueue(label: "MacClipboard.storage", qos: .userInitiated)
    private let pasteboard = NSPasteboard.general
    private var lastChangeCount: Int
    private var timer: Timer?
    private var cancellables = Set<AnyCancellable>()

    init(settings: AppSettings) {
        self.settings = settings
        self.lastChangeCount = pasteboard.changeCount

        let service = Bundle.main.bundleIdentifier ?? "io.github.anil3a.MacClipboard"
        do {
            let key = try KeychainKeyStore(service: service, account: "history-encryption-key").loadOrCreateKey()
            storage = HistoryStorage(root: HistoryStorage.defaultRoot(), cipher: HistoryCipher(key: key))
            isPersistent = true
        } catch {
            NSLog("MacClipboard: Keychain unavailable, history will not be saved: \(error)")
            // Still encrypt, but with a throwaway key in a temp folder that is deleted on quit.
            let temp = FileManager.default.temporaryDirectory.appendingPathComponent("MacClipboard-\(UUID().uuidString)")
            storage = HistoryStorage(root: temp, cipher: HistoryCipher(key: SymmetricKey(size: .bits256)))
            isPersistent = false
            storageProblem = "History can't be kept after quitting because the encryption key in your Keychain isn't available. \(error.localizedDescription)"
        }

        settings.$historyLimit
            .dropFirst()
            .sink { [weak self] limit in self?.trim(limit: limit) }
            .store(in: &cancellables)
    }

    // MARK: Lifecycle

    /// Loads saved history, then starts watching the pasteboard.
    func start() {
        let keepUnpinned = settings.keepAfterRestart && isPersistent
        io.async { [storage] in
            var loaded = storage.loadAll()
            if !keepUnpinned {
                loaded.filter { !$0.isPinned }.forEach { storage.deleteItem($0.id) }
                loaded.removeAll { !$0.isPinned }
                try? storage.saveIndex(loaded)
            }
            DispatchQueue.main.async {
                self.items = loaded
                self.trim(limit: self.settings.historyLimit)
                self.lastChangeCount = self.pasteboard.changeCount
                self.startTimer()
            }
        }
    }

    /// Called on quit. Makes sure pending writes finish and removes what shouldn't be kept.
    func prepareForTermination() {
        timer?.invalidate()
        let keepUnpinned = settings.keepAfterRestart && isPersistent
        let removed = keepUnpinned ? [] : items.filter { !$0.isPinned }.map(\.id)
        let kept = keepUnpinned ? items : items.filter(\.isPinned)
        let persistent = isPersistent
        io.sync { [storage] in
            removed.forEach(storage.deleteItem)
            try? storage.saveIndex(kept)
            if !persistent { storage.destroy() }
        }
    }

    private func startTimer() {
        let timer = Timer(timeInterval: 0.4, repeats: true) { [weak self] _ in self?.poll() }
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    // MARK: Capturing

    private func poll() {
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count
        guard settings.isEnabled, !shouldIgnoreCurrentCopy(), let snapshot = readPasteboard() else { return }

        let id = UUID()
        let date = Date()
        io.async {
            let result = ItemAnalyzer.analyze(snapshot, id: id, date: date)
            DispatchQueue.main.async { self.add(result, snapshot: snapshot) }
        }
    }

    private func shouldIgnoreCurrentCopy() -> Bool {
        let types = Set(pasteboard.types?.map(\.rawValue) ?? [])
        if !types.isDisjoint(with: Self.ignoredMarkerTypes) { return true }
        if settings.ignorePasswordManagers,
           let bundleID = NSWorkspace.shared.frontmostApplication?.bundleIdentifier,
           Self.passwordManagerBundleIDs.contains(bundleID) {
            return true
        }
        return false
    }

    private func readPasteboard() -> PasteboardSnapshot? {
        guard let pbItems = pasteboard.pasteboardItems, !pbItems.isEmpty else { return nil }
        return read(pbItems, allowed: nil) ?? read(pbItems, allowed: Self.essentialTypes)
    }

    /// Returns nil when the copy is larger than `maxItemBytes`.
    private func read(_ pbItems: [NSPasteboardItem], allowed: Set<String>?) -> PasteboardSnapshot? {
        var total = 0
        var snapshot: PasteboardSnapshot = []
        for pbItem in pbItems {
            let types = pbItem.types.map(\.rawValue)
            let hasUTF8 = types.contains(ItemAnalyzer.utf8Text)
            var reps: [PasteboardRepresentation] = []
            for type in types where Self.shouldStore(type, hasUTF8: hasUTF8) {
                if let allowed, !allowed.contains(type) { continue }
                guard let data = pbItem.data(forType: NSPasteboard.PasteboardType(type)) else { continue }
                total += data.count
                if total > Self.maxItemBytes { return nil }
                reps.append(PasteboardRepresentation(type: type, data: data))
            }
            if !reps.isEmpty { snapshot.append(reps) }
        }
        return snapshot.isEmpty ? nil : snapshot
    }

    /// Skips types macOS re-creates by itself, so long text isn't stored three or four times.
    static func shouldStore(_ type: String, hasUTF8: Bool) -> Bool {
        // Legacy names such as "NSStringPboardType" are aliases of the modern UTIs.
        guard type.contains(".") else { return false }
        if type.hasPrefix("dyn.") || type.hasPrefix("com.apple.pasteboard.promised") { return false }
        if type == "public.utf16-external-plain-text" || type == "com.apple.traditional-mac-plain-text" { return false }
        if hasUTF8 && type == ItemAnalyzer.utf16Text { return false }
        return true
    }

    private func add(_ result: ItemAnalyzer.Result, snapshot: PasteboardSnapshot) {
        if let index = items.firstIndex(where: { $0.contentHash == result.item.contentHash }) {
            // Same content copied again: move the existing entry to the top.
            var existing = items.remove(at: index)
            existing.date = result.item.date
            items.insert(existing, at: 0)
            persistIndex()
            return
        }

        let item = result.item
        items.insert(item, at: 0)
        io.async { [storage] in
            do {
                try storage.saveItem(item.id, snapshot: snapshot, thumbnailPNG: result.thumbnailPNG)
            } catch {
                NSLog("MacClipboard: could not save item: \(error)")
                storage.deleteItem(item.id)
                DispatchQueue.main.async {
                    self.items.removeAll { $0.id == item.id }
                    self.persistIndex()
                }
            }
        }
        trim(limit: settings.historyLimit)
    }

    private func trim(limit: Int) {
        var unpinnedCount = 0
        var removed: [UUID] = []
        items.removeAll { item in
            guard !item.isPinned else { return false }
            unpinnedCount += 1
            if unpinnedCount > limit {
                removed.append(item.id)
                return true
            }
            return false
        }
        if !removed.isEmpty {
            io.async { [storage] in removed.forEach(storage.deleteItem) }
        }
        persistIndex()
    }

    private func persistIndex() {
        let snapshot = items
        io.async { [storage] in
            do { try storage.saveIndex(snapshot) } catch { NSLog("MacClipboard: could not save index: \(error)") }
        }
    }

    // MARK: Actions

    /// Loads the item's data from disk, puts it on the system pasteboard and moves it to the top.
    func copyToPasteboard(_ item: ClipboardItem, plainTextOnly: Bool = false, completion: @escaping (Bool) -> Void) {
        io.async { [storage] in
            let snapshot = try? storage.loadSnapshot(item.id)
            DispatchQueue.main.async {
                guard let snapshot else { completion(false); return }
                self.pasteboard.clearContents()
                if plainTextOnly, let text = ItemAnalyzer.plainText(in: snapshot) {
                    self.pasteboard.setString(text, forType: .string)
                } else {
                    let pbItems = snapshot.map { reps -> NSPasteboardItem in
                        let pbItem = NSPasteboardItem()
                        for rep in reps { pbItem.setData(rep.data, forType: NSPasteboard.PasteboardType(rep.type)) }
                        return pbItem
                    }
                    self.pasteboard.writeObjects(pbItems)
                }
                self.lastChangeCount = self.pasteboard.changeCount

                if let index = self.items.firstIndex(where: { $0.id == item.id }) {
                    var moved = self.items.remove(at: index)
                    moved.date = Date()
                    self.items.insert(moved, at: 0)
                    self.persistIndex()
                }
                completion(true)
            }
        }
    }

    func togglePin(_ id: UUID) {
        guard let index = items.firstIndex(where: { $0.id == id }) else { return }
        items[index].isPinned.toggle()
        trim(limit: settings.historyLimit)
    }

    func delete(_ id: UUID) {
        items.removeAll { $0.id == id }
        io.async { [storage] in storage.deleteItem(id) }
        persistIndex()
    }

    /// Like Windows' "Clear all": removes everything except pinned items.
    func clearUnpinned() {
        let removed = items.filter { !$0.isPinned }.map(\.id)
        items.removeAll { !$0.isPinned }
        io.async { [storage] in removed.forEach(storage.deleteItem) }
        persistIndex()
    }

    /// Removes everything, pinned items included.
    func eraseAll() {
        items.removeAll()
        io.async { [storage] in storage.removeOrphans(keeping: []) }
        persistIndex()
        refreshDiskUsage()
    }

    func refreshDiskUsage() {
        io.async { [storage] in
            let usage = storage.diskUsage()
            DispatchQueue.main.async { self.diskUsage = usage }
        }
    }
}
